#!/usr/bin/env bash
# Start MediaMTX with lab config + XIAO auto-publish (official runOnInit pattern).
#
# MediaMTX itself can run forever. The ESP camera cannot hold one MJPEG TCP
# forever — so runOnInitRestart re-launches publish_xiao whenever it exits.
#
# Usage (one terminal on Mini):
#   ./scripts/mediamtx_run.sh
#   XIAO_MJPEG_URL=http://10.128.93.25:81/stream ./scripts/mediamtx_run.sh
#
# External publish (two terminals, old style):
#   XIAO_EXTERNAL_PUBLISH=1 ./scripts/mediamtx_run.sh
#   ./scripts/publish_xiao.sh http://10.128.93.25:81/stream
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CONF_SRC="$ROOT/mediamtx/mediamtx.yml"
CONF_RT="$ROOT/mediamtx/mediamtx.runtime.yml"
WRAPPER="$ROOT/mediamtx/run_xiao_publish.sh"
PUBLISH="$ROOT/scripts/publish_xiao.sh"
XIAO_URL="${XIAO_MJPEG_URL:-http://10.128.93.25:81/stream}"

if ! command -v mediamtx >/dev/null 2>&1; then
  echo "mediamtx not found. Install: brew install mediamtx" >&2
  exit 1
fi

if [[ ! -f "$CONF_SRC" ]]; then
  echo "missing config: $CONF_SRC" >&2
  exit 1
fi

chmod +x "$PUBLISH" 2>/dev/null || true

if lsof -nP -iTCP:8554 -sTCP:LISTEN >/dev/null 2>&1; then
  echo "Port 8554 is already in use." >&2
  echo "If Homebrew started MediaMTX:  brew services stop mediamtx" >&2
  exit 1
fi

if [[ "${XIAO_EXTERNAL_PUBLISH:-0}" == "1" ]]; then
  INIT_CMD="/usr/bin/true"
  echo "XIAO_EXTERNAL_PUBLISH=1 — start publish yourself:" >&2
  echo "  $PUBLISH $XIAO_URL" >&2
else
  # Thin wrapper so YAML runOnInit is a single executable path (MediaMTX docs style).
  cat >"$WRAPPER" <<EOF
#!/bin/bash
# Auto-generated by mediamtx_run.sh — do not edit.
export PUBLISH_ONCE=1
export PUBLISH_MODE="\${PUBLISH_MODE:-capture}"
exec "$PUBLISH" "$XIAO_URL"
EOF
  chmod +x "$WRAPPER"
  INIT_CMD="$WRAPPER"
fi

sed "s|__CAM_XIAO_RUN_ON_INIT__|${INIT_CMD}|" "$CONF_SRC" >"$CONF_RT"

echo "MediaMTX lab config: $CONF_RT" >&2
echo "  XIAO source: $XIAO_URL  (capture polls + MTX restart = continuous)" >&2
echo "  HLS    http://127.0.0.1:8888/cam_xiao/" >&2
echo "  WebRTC http://127.0.0.1:8889/cam_xiao/" >&2
echo "  Colleague HLS:    http://10.128.93.23:8888/cam_xiao/" >&2
echo "  Colleague WebRTC: http://10.128.93.23:8889/cam_xiao/" >&2
echo "  RTSP   rtsp://10.128.93.23:8554/cam_xiao" >&2
echo "Ctrl+C to stop (stops MTX + auto-publish)." >&2

exec mediamtx "$CONF_RT"
