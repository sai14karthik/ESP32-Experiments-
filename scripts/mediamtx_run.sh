#!/usr/bin/env bash
# One command: MediaMTX + ESP→H.264 bridge (continuous for lab).
#
# Official MediaMTX path for ESP32 MJPEG cameras:
#   FFmpeg in runOnInit (+ runOnInitRestart) publishes into MediaMTX.
#   Viewers use HLS / WebRTC / RTSP from MediaMTX — not from the ESP.
#
# Refs:
#   https://github.com/bluenviron/mediamtx/discussions/3575
#   https://mediamtx.org/docs/usage/hooks
#   https://mediamtx.org/docs/publish/ffmpeg
#   https://mediamtx.org/docs/read/hls
#
# Board firmware: firmware/CameraWebServerWiFi (http://<ip>/ and :81/stream)
#
# Usage (Mini):
#   ./scripts/mediamtx_run.sh
#   XIAO_MJPEG_URL=http://10.128.93.25:81/stream ./scripts/mediamtx_run.sh
#
# External publish (two terminals):
#   XIAO_EXTERNAL_PUBLISH=1 ./scripts/mediamtx_run.sh
#   ./scripts/publish_xiao.sh http://10.128.93.25:81/stream
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CONF_SRC="$ROOT/mediamtx/mediamtx.yml"
CONF_RT="$ROOT/mediamtx/mediamtx.runtime.yml"
WRAPPER="$ROOT/mediamtx/run_xiao_publish.sh"
PUBLISH="$ROOT/scripts/publish_xiao.sh"
XIAO_URL="${XIAO_MJPEG_URL:-http://10.128.93.25:81/stream}"
MODE="${PUBLISH_MODE:-capture}"

if ! command -v mediamtx >/dev/null 2>&1; then
  echo "mediamtx not found. Install: brew install mediamtx" >&2
  exit 1
fi
if ! command -v ffmpeg >/dev/null 2>&1; then
  echo "ffmpeg not found. Install: brew install ffmpeg" >&2
  exit 1
fi
if [[ ! -f "$CONF_SRC" ]]; then
  echo "missing config: $CONF_SRC" >&2
  exit 1
fi

chmod +x "$PUBLISH" 2>/dev/null || true

if lsof -nP -iTCP:8554 -sTCP:LISTEN >/dev/null 2>&1; then
  echo "Port 8554 is already in use." >&2
  echo "Stop leftovers:  pkill -f mediamtx; pkill -f publish_xiao; pkill -f 'ffmpeg.*cam_xiao'" >&2
  echo "Or:  brew services stop mediamtx" >&2
  exit 1
fi

if [[ "${XIAO_EXTERNAL_PUBLISH:-0}" == "1" ]]; then
  INIT_CMD="/usr/bin/true"
  echo "XIAO_EXTERNAL_PUBLISH=1 — start publish yourself:" >&2
  echo "  PUBLISH_MODE=$MODE $PUBLISH $XIAO_URL" >&2
else
  cat >"$WRAPPER" <<EOF
#!/bin/bash
# Auto-generated by mediamtx_run.sh — do not edit.
# MediaMTX runOnInit: one foreground publisher; restart on exit.
export PUBLISH_ONCE=1
export PUBLISH_MODE="${MODE}"
exec "$PUBLISH" "$XIAO_URL"
EOF
  chmod +x "$WRAPPER"
  INIT_CMD="$WRAPPER"
fi

# Escape for sed replacement
INIT_ESC="$(printf '%s' "$INIT_CMD" | sed 's/[&/\]/\\&/g')"
sed "s|__CAM_XIAO_RUN_ON_INIT__|${INIT_ESC}|" "$CONF_SRC" >"$CONF_RT"

echo "MediaMTX + ESP bridge" >&2
echo "  config : $CONF_RT" >&2
echo "  ESP    : $XIAO_URL  (mode=$MODE)" >&2
echo "  Browsers (colleague):" >&2
echo "    HLS    http://10.128.93.23:8888/cam_xiao/" >&2
echo "    WebRTC http://10.128.93.23:8889/cam_xiao/" >&2
echo "  Local:" >&2
echo "    HLS    http://127.0.0.1:8888/cam_xiao/" >&2
echo "    WebRTC http://127.0.0.1:8889/cam_xiao/" >&2
echo "    RTSP   rtsp://127.0.0.1:8554/cam_xiao" >&2
echo "Ctrl+C stops MediaMTX + bridge." >&2

exec mediamtx "$CONF_RT"
